"""
WP-5: bounded retries + progress deadlines for remote range reads.

HttpClient.get_many() now retries individual range requests that fail with a
transient cause (5xx/429 or a connection/timeout/partial-transfer CURL error),
with exponential backoff + jitter, up to OPTERYX_HTTP_MAX_RETRIES (default 2).
4xx (except 429) is a hard error and is NOT retried. Exhausted retries raise a
clear error naming the cause, url, and range.

These tests drive the real C++ client against dev/throttle_server.py with
injected faults. Retry config is read once per process into statics, so the
suite runs with the default (2 retries) — tests are designed around that.
"""

import os
import subprocess
import sys
import time

import pytest

sys.path.insert(1, os.path.join(sys.path[0], "../../../.."))

DATA_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../../dev/bench_data")
DATA_DIR = os.path.abspath(DATA_DIR)
SERVER = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../../dev/throttle_server.py")
SERVER = os.path.abspath(SERVER)
FNAME = "remote_io_bench.parquet"


# The batch-budget test reads 12 ranges of 256 KiB (3 MiB) from the file, and a
# range past the end of the file is a 416, not a short read. A generated stand-in
# must therefore hold more than that on disk, which sequential ids (compressed to
# almost nothing) and an 800 KB file did not.
_GENERATED_ROWS = 1 << 19   # 4 MiB of int64, stored uncompressed


def _ensure_data():
    """The bench dataset is generated by dev/bench_remote_io.py; create it if absent."""
    path = os.path.join(DATA_DIR, FNAME)
    if not os.path.isfile(path):
        import random

        import pyarrow as pa
        import pyarrow.parquet as pq

        os.makedirs(DATA_DIR, exist_ok=True)
        rng = random.Random(1)
        ids = [rng.getrandbits(62) for _ in range(_GENERATED_ROWS)]
        t = pa.table({"id": pa.array(ids, type=pa.int64())})
        pq.write_table(t, path, compression="NONE", use_dictionary=False)
    return path


def _server(error_rate=0.0, seed=1):
    proc = subprocess.Popen(
        [sys.executable, SERVER, "--root", DATA_DIR, "--port", "0",
         "--error-rate", str(error_rate), "--seed", str(seed)],
        stdout=subprocess.PIPE, text=True,
    )
    port = int(proc.stdout.readline().strip().split("port=")[1])
    return proc, port


def _url(port):
    return f"http://127.0.0.1:{port}/{FNAME}"


def test_no_fault_succeeds():
    from opteryx.compiled.http_client import HttpClient

    _ensure_data()
    proc, port = _server(0.0)
    try:
        out = HttpClient().get_many([(_url(port), {"Range": "bytes=0-4095"})])
        assert len(out[0]) == 4096
    finally:
        proc.kill(); proc.wait()


def test_persistent_5xx_raises_exhausted():
    from opteryx.compiled.http_client import HttpClient

    _ensure_data()
    proc, port = _server(1.0)  # every request 503
    try:
        with pytest.raises(RuntimeError) as ei:
            HttpClient().get_many([(_url(port), {"Range": "bytes=0-1023"})])
        assert "exhaust" in str(ei.value).lower()
    finally:
        proc.kill(); proc.wait()


def test_4xx_not_retried_and_immediate():
    from opteryx.compiled.http_client import HttpClient

    _ensure_data()
    proc, port = _server(0.0)
    try:
        t0 = time.monotonic()
        with pytest.raises(RuntimeError) as ei:
            HttpClient().get_many([(f"http://127.0.0.1:{port}/missing.parquet", {"Range": "bytes=0-1023"})])
        elapsed = time.monotonic() - t0
        assert "404" in str(ei.value)
        # No retry/backoff on a 4xx — should return effectively immediately.
        assert elapsed < 1.0, f"4xx took {elapsed:.2f}s, suggesting it was retried"
    finally:
        proc.kill(); proc.wait()


def test_ssl_connect_error_is_retried():
    """A TLS handshake failure is transient (seen live against GCS under load),
    so it retries like a timeout. An https:// URL at the plain-HTTP throttle
    server fails the handshake deterministically with CURLE_SSL_CONNECT_ERROR;
    the error must be the retries-exhausted form, not an immediate hard failure."""
    from opteryx.compiled.http_client import HttpClient

    _ensure_data()
    proc, port = _server(0.0)
    try:
        with pytest.raises(RuntimeError) as ei:
            HttpClient().get_many([(f"https://127.0.0.1:{port}/{FNAME}", {"Range": "bytes=0-1023"})])
        assert "exhaust" in str(ei.value).lower(), str(ei.value)
        assert "SSL connect error" in str(ei.value), str(ei.value)
    finally:
        proc.kill(); proc.wait()


def test_transient_faults_recover():
    """With a 30% transient fault rate and the default 2 retries (3 attempts),
    P(recover) per request is 1 - 0.3**3 ≈ 0.973, so essentially every read
    should succeed. Assert a strong majority across trials (loose bound to stay
    robust to the seeded fault sequence)."""
    from opteryx.compiled.http_client import HttpClient

    _ensure_data()
    proc, port = _server(0.3, seed=11)
    try:
        c = HttpClient()
        recovered = 0
        trials = 20
        for i in range(trials):
            try:
                out = c.get_many([(_url(port), {"Range": f"bytes={i*64}-{i*64+1023}"})])
                recovered += len(out[0]) == 1024
            except RuntimeError:
                pass
        # Without retries this would be ~70%; with retries expect ≥90%.
        assert recovered >= int(trials * 0.85), f"only {recovered}/{trials} recovered"
    finally:
        proc.kill(); proc.wait()


# Deadlines are progress-based (docs/REMOTE_READ_FLOW_CONTROL_DESIGN.md §4.1): a
# transfer fails when no byte arrives for OPTERYX_HTTP_STALL_MS, or at
# OPTERYX_HTTP_CEILING_MS. Runs in a child so those env values (read once per
# process into statics) apply.
_DEADLINE_CHILD = r"""
import sys, time
from opteryx.compiled.http_client import HttpClient
url, n, size = sys.argv[1], int(sys.argv[2]), int(sys.argv[3])
reqs = [(url, {"Range": f"bytes={i * size}-{(i + 1) * size - 1}"}) for i in range(n)]
t0 = time.monotonic()
try:
    out = HttpClient().get_many(reqs)
    assert all(len(b) == size for b in out)
    print(f"OK {time.monotonic() - t0:.2f}")
except RuntimeError as e:
    print(f"ERR {time.monotonic() - t0:.2f} {e}")
"""


def _deadline_run(server_args, n, size, **env):
    _ensure_data()
    proc = subprocess.Popen(
        [sys.executable, SERVER, "--root", DATA_DIR, "--port", "0", *server_args],
        stdout=subprocess.PIPE, text=True,
    )
    port = int(proc.stdout.readline().strip().split("port=")[1])
    try:
        root = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../../.."))
        res = subprocess.run(
            [sys.executable, "-c", _DEADLINE_CHILD, _url(port), str(n), str(size)],
            env=dict(os.environ, **env), cwd=root, capture_output=True, text=True, timeout=60,
        )
        out = res.stdout.strip() or res.stderr.strip()
        status, elapsed, *rest = out.split(" ", 2)
        return status, float(elapsed), (rest[0] if rest else "")
    finally:
        proc.kill(); proc.wait()


def test_slow_wide_batch_completes_under_a_short_stall():
    """24 ranges share 3 connections on a 4 Mbps-per-connection link: ~2 s in all,
    so most ranges wait well past the 1 s stall before their first byte. A busy
    link is not a stall - queued ranges must not time out - and the batch is not
    bounded by a size-derived budget any more."""
    status, elapsed, detail = _deadline_run(
        ["--bandwidth-mbps", "4"], 24, 128 * 1024,
        OPTERYX_HTTP_STALL_MS="1000", OPTERYX_HTTP_MAX_RETRIES="0",
    )
    assert status == "OK", detail
    assert elapsed > 1.5, f"link not slow enough to test queueing: {elapsed:.2f}s"


def test_dead_link_fails_promptly_as_a_stall():
    """Headers, 1000 body bytes, then nothing on an open connection."""
    status, elapsed, detail = _deadline_run(
        ["--stall-after-bytes", "1000"], 1, 64 * 1024,
        OPTERYX_HTTP_STALL_MS="1000", OPTERYX_HTTP_MAX_RETRIES="0",
    )
    assert status == "ERR", detail
    assert "stalled (no bytes for 1000ms)" in detail, detail
    assert "received=1000/65536B" in detail, detail
    assert elapsed < 3.0, f"stall took {elapsed:.2f}s to fail"


def test_crawling_link_fails_at_the_ceiling():
    """2 MiB at 1 MB/s keeps moving (never a stall) but outlives an 800 ms ceiling."""
    status, elapsed, detail = _deadline_run(
        ["--bandwidth-mbps", "8"], 1, 2 * 1024 * 1024,
        OPTERYX_HTTP_STALL_MS="5000", OPTERYX_HTTP_CEILING_MS="800", OPTERYX_HTTP_MAX_RETRIES="0",
    )
    assert status == "ERR", detail
    assert "exceeded the 800ms ceiling" in detail, detail
    assert elapsed < 2.0, f"ceiling took {elapsed:.2f}s to fire"


if __name__ == "__main__":
    test_no_fault_succeeds(); print("no-fault: OK")
    test_persistent_5xx_raises_exhausted(); print("persistent 5xx exhausted: OK")
    test_4xx_not_retried_and_immediate(); print("4xx immediate, no retry: OK")
    test_transient_faults_recover(); print("transient recover: OK")
    test_slow_wide_batch_completes_under_a_short_stall(); print("slow wide batch: OK")
    test_dead_link_fails_promptly_as_a_stall(); print("dead link stall: OK")
    test_crawling_link_fails_at_the_ceiling(); print("ceiling: OK")
    print("all WP-5 tests passed")
