TIMESTAMP_US = TIMESTAMP(TimestampUnit.MICROSECONDS)

from opteryx.expression.intervals import MICROSECONDS_PER_DAY as US_PER_DAY


def interval(months, microseconds):
    """A stand-in for an INTERVAL literal node: value plus the `type` tag
    `_resolve_offset` reads to tell an interval from a number."""

    class _Literal:
        def __init__(self):
            from opteryx.types.logical_type import INTERVAL

            self.value = (months, microseconds)
            self.type = INTERVAL

    return _Literal()


def number(value, column_type=INT64):
    class _Literal:
        def __init__(self):
            self.value = value
            self.type = column_type

    return _Literal()


def test_no_offset_resolves_to_zero():
    assert _resolve_offset([], TIMESTAMP_US) == 0
    assert _resolve_offset([], DATE) == 0
    assert _resolve_offset([], INT64) == 0


@pytest.mark.parametrize("sign", (1, -1))
def test_timestamp_offset_is_microseconds(sign):
    assert _resolve_offset([(interval(0, 20_000_000), sign)], TIMESTAMP_US) == sign * 20_000_000


@pytest.mark.parametrize("sign", (1, -1))
def test_date_offset_is_days(sign):
    """The INTERVAL carries microseconds; DATE32 counts days. Reading the µs count as
    a day count is the silent-1970 bug in its purest form."""
    assert _resolve_offset([(interval(0, 2 * US_PER_DAY), sign)], DATE) == sign * 2


def test_a_month_offset_declines():
    """`interval_apply_to_temporal` applies months as calendar arithmetic with
    end-of-month clamping — 31 days from January, 28 from February. No number
    describes it."""
    assert _resolve_offset([(interval(1, 0), 1)], TIMESTAMP_US) is None
    assert _resolve_offset([(interval(1, 0), 1)], DATE) is None
    assert _resolve_offset([(interval(1, US_PER_DAY), 1)], DATE) is None


def test_a_sub_day_offset_declines_on_a_date():
    assert _resolve_offset([(interval(0, US_PER_DAY // 2), 1)], DATE) is None
    # ... but is exact on a microsecond timestamp.
    assert _resolve_offset([(interval(0, US_PER_DAY // 2), 1)], TIMESTAMP_US) == US_PER_DAY // 2


def test_offsets_on_both_operands_combine():
    """`Lcol + dl <op> Rcol + dr` is `Lcol <op> Rcol + (dr - dl)`."""
    terms = [(interval(0, 5 * US_PER_DAY), 1), (interval(0, 2 * US_PER_DAY), -1)]
    assert _resolve_offset(terms, DATE) == 3


def test_a_numeric_offset_must_be_an_integer():
    assert _resolve_offset([(number(5), 1)], INT64) == 5
    assert _resolve_offset([(number(5), -1)], INT64) == -5
    # A float offset makes the sum a rounding question whose safe direction depends
    # on which bound is being shifted; declining is the sound answer.
    from opteryx.types.logical_type import FLOAT64

    assert _resolve_offset([(number(0.5, FLOAT64), 1)], FLOAT64) is None


def test_an_interval_offset_declines_on_a_number_and_a_number_on_a_temporal():
    assert _resolve_offset([(interval(0, US_PER_DAY), 1)], INT64) is None
    assert _resolve_offset([(number(5), 1)], TIMESTAMP_US) is None
    assert _resolve_offset([(number(5), 1)], DATE) is None


def test_shift_crosses_a_day_boundary_in_both_directions():
    """2024-03-10 00:00:10 UTC, shifted back 20 seconds, is on 2024-03-09."""
    start = datetime.datetime(2024, 3, 10, 0, 0, 10, tzinfo=datetime.timezone.utc)
    start_us = int(start.timestamp()) * 1_000_000
    shifted = _shifted(ColumnRange(lower_bound=start_us, upper_bound=start_us), -20_000_000, "both")
    expected = datetime.datetime(2024, 3, 9, 23, 59, 50, tzinfo=datetime.timezone.utc)
    assert shifted.lower_bound == int(expected.timestamp()) * 1_000_000
    assert shifted.upper_bound == shifted.lower_bound

    forward = _shifted(ColumnRange(lower_bound=start_us, upper_bound=start_us), +20_000_000, "both")
    assert forward.lower_bound == start_us + 20_000_000

    # DATE32, in days, over the same boundary.
    march_10 = (datetime.date(2024, 3, 10) - datetime.date(1970, 1, 1)).days
    back = _shifted(ColumnRange(lower_bound=march_10, upper_bound=march_10), -2, "both")
    assert back.lower_bound == (datetime.date(2024, 3, 8) - datetime.date(1970, 1, 1)).days


def test_shift_keeps_only_the_bound_the_comparator_establishes():
    original = ColumnRange(lower_bound=10, upper_bound=20)
    assert _shifted(original, 5, "both") == ColumnRange(lower_bound=15, upper_bound=25)
    assert _shifted(original, 5, "upper") == ColumnRange(lower_bound=None, upper_bound=25)
    assert _shifted(original, 5, "lower") == ColumnRange(lower_bound=15, upper_bound=None)
    # A one-sided source range narrowed to its missing end has nothing to transport.
    assert _shifted(ColumnRange(lower_bound=10, upper_bound=None), 5, "upper") is None


def test_temporal_bounds_are_carried_in_their_native_encoding():
    """`value_range` holds the column's native int — microseconds for TIMESTAMP64,
    days for DATE32 — and `build_literal_node` passes an int through untouched, so
    the coercion is an identity. No datetime is ever constructed, which is what keeps
    the DATE32-read-as-microseconds bound out of this path."""
    from opteryx.types.logical_type import LogicalCategory

    assert (
        _coerce_temporal_bound(1_710_028_790_000_000, TIMESTAMP_US, LogicalCategory.TIMESTAMP)
        == 1_710_028_790_000_000
    )
    assert _coerce_temporal_bound(19_790, DATE, LogicalCategory.DATE) == 19_790

    # A float bound would mean an inlet wrote a value `value_range` does not hold.
    assert _coerce_temporal_bound(19_790.0, DATE, LogicalCategory.DATE) is None
    # Out of the physical width — the literal would die on materialisation.
    assert _coerce_temporal_bound(2**31, DATE, LogicalCategory.DATE) is None
    assert _coerce_temporal_bound(-(2**31) - 1, DATE, LogicalCategory.DATE) is None
    # A non-microsecond timestamp declines because the two inlets of `value_range`
    # disagree on its unit: the manifest contributes the footer's raw milliseconds,
    # while a bound harvested from a predicate literal is microseconds (
    # `build_literal_node` runs `timestamp_to_int64_us` regardless of the declared
    # unit). The bound's unit is therefore not knowable from its type.
    assert (
        _coerce_temporal_bound(
            1_710_028_790_000, TIMESTAMP(TimestampUnit.MILLISECONDS), LogicalCategory.TIMESTAMP
        )
        is None
    )


def test_time_columns_never_receive_a_pushed_bound():
    """TIME has no working column type in this engine — a scan yields raw ints, CAST
    yields raw ticks, and the operator map has no TIME rows. A bound pushed onto one
    would be compared in a space nothing else agrees on."""
    from opteryx.planner.optimizer.strategies.correlated_filters import _coerce_bound

    assert _coerce_bound(1_000_000, TIME(), True) is None
    assert _coerce_bound(1_000_000, TIME(), False) is None


