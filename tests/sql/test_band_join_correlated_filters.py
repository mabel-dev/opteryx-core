"""A band join's realized value range bounds the OTHER leg, shifted by the band's offset.

CorrelatedFiltersStrategy reads each join key's propagated range and pushes it onto
the opposite leg's scan as a necessary condition for a match. That argument was
implemented for equi-joins only, but it never depended on equality:

    l.event_time <= f.flow_start
    l.event_time  > f.flow_start - INTERVAL '20' SECOND     f.flow_start in [lo, hi]

    => any matching l.event_time is in (lo - 20s, hi]

Same necessary condition, bounds displaced by the offset. An equi-join is the
zero-offset case that happens to establish BOTH ends at once; a band establishes
one end per conjunct.

WHAT THIS FILE PINS

A shifted bound that is off by one tick, or shifted the wrong way, DELETES JOINED
ROWS. Nothing raises, no count looks implausible, and the answer stays perfectly
self-consistent — it is simply missing rows. So every query here is compared
row-for-row against TWO oracles: the same query with CorrelatedFiltersStrategy
switched off, and the same query with PredicatePushdownStrategy switched off (where
the band is a Filter above the join and no range can be derived at all).

The rows that matter are the WINDOW EDGES, and the fixture puts one ONE MICROSECOND
either side of every bound the optimizer computes. `lo_plus1us` is the sharp one: it
sits one microsecond inside the derived lower bound, so ANY understatement of the
20-second shift drops it. `test_the_ranges_are_actually_pushed` exists because
without it every assertion above would still pass if the rule quietly declined
everything — which is exactly what it did for temporal columns before this change.

DAY BOUNDARIES: `flows.a` starts at 00:00:10, so its -20s bound lands on the
PREVIOUS day at 23:59:50, and `flows.d`'s window opens the evening before. A shift
computed in the wrong unit — days read as microseconds, the "silent 1970 bound" —
cannot survive either.

Fixture: `testdata/band_join/`, regenerated by `dev/generate_band_join_fixture.py`.
It is a real parquet scan on purpose: this rule needs a connector, footer min/max
and propagated statistics, so a VALUES relation would exercise none of it.

Related: `test_band_join_absorption.py`, which pins the step BEFORE this one — a
cross-relation band in the WHERE reaching the join's ON at all.
"""

