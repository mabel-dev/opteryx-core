FLOWS = "testdata.band_join.flows"
LOOKUPS = "testdata.band_join.lookups"

# `l.event_time` in (min(flow_start) - 20s, max(flow_start)] is the necessary
# condition; both ends are transported, from two separate conjuncts.
TIMESTAMP_BAND = f"""
SELECT f.client, l.tag
  FROM {FLOWS} f INNER JOIN {LOOKUPS} l ON f.client = l.client
 WHERE l.event_time <= f.flow_start
   AND l.event_time > f.flow_start - INTERVAL '20' SECOND
 ORDER BY l.tag
"""

# Only the upper end exists here, so only the upper bound may be transported.
TIMESTAMP_ONE_SIDED = f"""
SELECT f.client, l.tag
  FROM {FLOWS} f INNER JOIN {LOOKUPS} l ON f.client = l.client
 WHERE l.event_time <= f.flow_start
 ORDER BY l.tag
"""

# DATE32 counts DAYS, so the INTERVAL's microseconds must be divided down before
# they can be added to a bound. Getting that wrong is the "silent 1970" bound.
DATE_BAND = f"""
SELECT f.client, l.tag
  FROM {FLOWS} f INNER JOIN {LOOKUPS} l ON f.client = l.client
 WHERE l.event_day <= f.flow_day
   AND l.event_day >= f.flow_day - INTERVAL '2' DAY
 ORDER BY l.tag
"""

# A sub-day offset on a DATE column has no exact day-unit spelling, and a MONTH is
# not a fixed displacement at all (the calendar kernel clamps to end-of-month). Both
# must DECLINE the shift rather than round it — and still answer correctly.
DATE_SUB_DAY_OFFSET = f"""
SELECT f.client, l.tag
  FROM {FLOWS} f INNER JOIN {LOOKUPS} l ON f.client = l.client
 WHERE l.event_day <= f.flow_day
   AND l.event_day >= f.flow_day - INTERVAL '12' HOUR
 ORDER BY l.tag
"""

TIMESTAMP_MONTH_OFFSET = f"""
SELECT f.client, l.tag
  FROM {FLOWS} f INNER JOIN {LOOKUPS} l ON f.client = l.client
 WHERE l.event_time <= f.flow_start
   AND l.event_time > f.flow_start - INTERVAL '1' MONTH
 ORDER BY l.tag
"""

# The zero-offset case. Both bounds, exactly as before this change.
EQUI = f"""
SELECT f.client, l.tag
  FROM {FLOWS} f INNER JOIN {LOOKUPS} l ON f.client = l.client
 WHERE l.event_time = f.flow_start
 ORDER BY l.tag
"""

# A preserved-side row that matches nothing must survive NULL-extended, so a
# match-necessary condition may not be pushed onto EITHER leg of an outer join.
# (This query's WHERE is inner-like — `NULL <= x` is false — but the join itself
# must still not be narrowed, and `visit` admits only inner / nested loop.)
OUTER_BAND = f"""
SELECT f.client, l.tag
  FROM {FLOWS} f LEFT OUTER JOIN {LOOKUPS} l ON f.client = l.client
 WHERE l.event_time <= f.flow_start
   AND l.event_time > f.flow_start - INTERVAL '20' SECOND
 ORDER BY l.tag
"""

# The inexact offsets ALONE. Written with the `<=` conjunct alongside them (as
# `DATE_BAND` is) the zero-offset half would push legitimately and mask the
# decline, so these carry the one conjunct whose shift cannot be expressed.
ONLY_SUB_DAY_OFFSET = f"""
SELECT f.client, l.tag
  FROM {FLOWS} f INNER JOIN {LOOKUPS} l ON f.client = l.client
 WHERE l.event_day >= f.flow_day - INTERVAL '12' HOUR
 ORDER BY l.tag
"""

ONLY_MONTH_OFFSET = f"""
SELECT f.client, l.tag
  FROM {FLOWS} f INNER JOIN {LOOKUPS} l ON f.client = l.client
 WHERE l.event_time > f.flow_start - INTERVAL '1' MONTH
 ORDER BY l.tag
"""

ALL_QUERIES = (
    TIMESTAMP_BAND,
    TIMESTAMP_ONE_SIDED,
    DATE_BAND,
    DATE_SUB_DAY_OFFSET,
    TIMESTAMP_MONTH_OFFSET,
    ONLY_SUB_DAY_OFFSET,
    ONLY_MONTH_OFFSET,
    EQUI,
    OUTER_BAND,
)


def rows(sql):
    """Every row, in order, as tuples — row-for-row comparison, not a count."""
    session = opteryx.session()
    out = []
    for morsel in session.execute_to_morsels(sql):
        if morsel is None:
            continue
        table = morsel.to_arrow().to_pydict()
        names = list(table.keys())
        out.extend(zip(*(table[name] for name in names)))
    return out


def rows_and_pushes(sql):
    """As `rows`, plus how many correlated range predicates the optimizer derived."""
    session = opteryx.session()
    out = []
    for morsel in session.execute_to_morsels(sql):
        if morsel is None:
            continue
        table = morsel.to_arrow().to_pydict()
        names = list(table.keys())
        out.extend(zip(*(table[name] for name in names)))
    return out, session.telemetry.get("optimization_inner_join_correlated_filter", 0)


@pytest.fixture
def without_correlated_filters():
    """The same plan with this rule switched off — every derived range removed, the
    join and its residual otherwise untouched. The tightest possible oracle."""
    original = config.features.disable_correlated_filters
    config.features.disable_correlated_filters = True
    try:
        yield rows
    finally:
        config.features.disable_correlated_filters = original


@pytest.fixture
def without_pushdown():
    """The same query with PredicatePushdownStrategy off, so the band never reaches
    the join's ON and no range can be derived from it at all."""
    original = config.features.disable_predicate_pushdown
    config.features.disable_predicate_pushdown = True
    try:
        yield rows
    finally:
        config.features.disable_predicate_pushdown = original


@pytest.mark.parametrize("sql", ALL_QUERIES)
def test_matches_the_plan_without_correlated_filters(sql, without_correlated_filters):
    assert rows(sql) == without_correlated_filters(sql), sql


@pytest.mark.parametrize("sql", ALL_QUERIES)
def test_matches_the_unoptimised_plan(sql, without_pushdown):
    assert rows(sql) == without_pushdown(sql), sql


def test_timestamp_band_window_edges():
    """`lo_plus1us` is one microsecond inside the derived lower bound and `hi_exact`
    sits exactly on the derived upper one; both must survive. `lo_exact` is on the
    OPEN end (`>`) and `a_plus1us` past the CLOSED one (`<=`), so both must not."""
    result = rows(TIMESTAMP_BAND)
    tags = {tag for _, tag in result}

    assert "lo_plus1us" in tags, result  # dies to any understated shift
    assert "lo_inside" in tags, result
    assert "a_exact" in tags, result  # `<=` is closed
    assert "hi_exact" in tags, result  # exactly on the transported upper bound
    assert "d_prev_evening" in tags, result  # window opens on the previous day

    assert "lo_exact" not in tags, result  # `>` is open
    assert "lo_minus1us" not in tags, result
    assert "a_plus1us" not in tags, result
    assert "hi_plus1us" not in tags, result
    assert "z_no_flow" not in tags, result  # no flow for this client at all

    assert result == [
        ("a", "a_exact"),
        ("a", "a_minus1us"),
        ("b", "b_inside"),
        ("b", "b_lo_plus1us"),
        ("c", "c_inside"),
        ("d", "d_exact"),
        ("d", "d_lo_plus1us"),
        ("d", "d_prev_evening"),
        ("e", "hi_exact"),
        ("e", "hi_minus1us"),
        ("a", "lo_inside"),
        ("a", "lo_plus1us"),
    ], result


def test_date_band_window_edges():
    """min(flow_day) is 2024-03-10, so the -2 day shift puts the derived lower bound
    on 2024-03-08 — `day_minus2` is ON it and `>=` is closed, so it must survive."""
    tags = {tag for _, tag in rows(DATE_BAND)}
    assert "day_minus2" in tags
    assert "day_minus1" in tags
    assert "day_minus3" not in tags


def test_the_ranges_are_actually_pushed():
    """Without this, every correctness assertion above passes vacuously — a rule that
    declines everything is trivially answer-preserving. Temporal columns declined
    exactly that way until the bound encoding was pinned down."""
    for sql in (TIMESTAMP_BAND, TIMESTAMP_ONE_SIDED, DATE_BAND, EQUI):
        _, pushes = rows_and_pushes(sql)
        assert pushes > 0, sql


def test_an_inexact_offset_declines_rather_than_rounds():
    """A half-day offset on a DATE column and a MONTH offset on a timestamp have no
    exact displacement in the target's unit. Declining costs pruning; rounding would
    cost rows."""
    for sql in (ONLY_SUB_DAY_OFFSET, ONLY_MONTH_OFFSET):
        _, pushes = rows_and_pushes(sql)
        assert pushes == 0, sql


def test_an_outer_join_gets_no_correlated_filter():
    """The pushed range is a necessary condition for a MATCH. An outer join emits its
    non-matching preserved rows NULL-extended, so narrowing either leg by it would
    delete rows that must survive. `visit` admits inner / nested loop only."""
    _, pushes = rows_and_pushes(OUTER_BAND)
    assert pushes == 0


